#!/bin/bash
# Regenerate the pinned Python lockfiles in app/requirements/ from the inputs in
# scripts/python-deps/*.in.
#
# The app installs these into its own venv, built on the python-build-standalone
# CPython 3.12 that src-tauri/src/python.rs downloads, so the pins are resolved
# for CPython 3.12 on Apple Silicon, wheels only (users have no compilers).
# Hashes are included: pip then refuses any file that doesn't match.
#
# core.txt is installed at launch; changing it makes the next launch re-sync the
# venv (python.rs stores the lockfile's SHA-256 in the venv). The extras are
# installed on demand by app/utils/system.py ensure_installed(..., extra=...),
# each constrained by core.txt and by the extras resolved before it, so a
# package pinned in two files always has the same version.
#
# Needs uv (brew install uv).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IN="$ROOT/scripts/python-deps"
OUT="$ROOT/app/requirements"
mkdir -p "$OUT"

compile() {
  local name="$1"
  shift
  uv pip compile "$IN/$name.in" \
    --python-version 3.12 \
    --python-platform aarch64-apple-darwin \
    --only-binary :all: \
    --generate-hashes \
    --no-header \
    --annotation-style line \
    --quiet \
    "$@" \
    -o "$OUT/$name.txt"
  # A short header that says where the file comes from.
  local tmp
  tmp="$(mktemp)"
  {
    echo "# Generated by scripts/lock-python-deps.sh from scripts/python-deps/$name.in."
    echo "# CPython 3.12, aarch64-apple-darwin, wheels only. Don't edit by hand."
    cat "$OUT/$name.txt"
  } >"$tmp"
  mv "$tmp" "$OUT/$name.txt"
  echo "$name.txt: $(grep -cE '^[A-Za-z0-9_.-]+==' "$OUT/$name.txt") packages"
}

compile core "$@"
# openai-whisper only ships an sdist (pure Python, builds with setuptools, no
# compiler needed): the one package allowed to build from source.
compile whisper -c "$OUT/core.txt" --no-binary openai-whisper "$@"
compile local-summary -c "$OUT/core.txt" -c "$OUT/whisper.txt" "$@"
compile diarize -c "$OUT/core.txt" -c "$OUT/whisper.txt" -c "$OUT/local-summary.txt" "$@"
